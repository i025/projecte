"""Opt-in API compatibility probe. Never imports or invokes a Blender runtime."""
import argparse
import ast
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import time
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from jsonschema import validate, ValidationError
from PIL import Image

from e_harness.model_client import ModelClient, token_counts
from e_harness.prompts import SYSTEM
from e_harness.storage import Storage
from e_harness.tools import TOOLS

MAX_OUTPUT_TOKENS = 2048
API_TIMEOUT = 60
FEEDBACK_NOTE = (
    "Fixture/simulated feedback: this image was rendered previously from a reviewed Mock program. "
    "It is NOT the result of your code or tool call. No tool was executed. "
    "Use it only to test visual feedback and choose one next native tool call."
)


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--model", required=True, help="LiteLLM provider/model identifier")
    p.add_argument("--image", type=Path, required=True)
    p.add_argument("--api-base-url")
    p.add_argument("--max-api-calls", type=int, choices=(1, 2), default=2)
    p.add_argument("--output", type=Path)
    p.add_argument("--feedback-image", type=Path, default=ROOT.parent / "bvb-repro/results/local_cpu/render.png",
                   help="Previously rendered trusted Mock PNG; never generated by this test")
    p.add_argument("--live", action="store_true", help="Authorize up to two billable API attempts")
    return p


def check_call(message, store, number):
    calls = message.get("tool_calls") or []
    if len(calls) != 1:
        return {"valid": False, "error": "Expected exactly one native tool call", "calls": calls}
    call = calls[0]
    result = {"valid": False, "call": call, "python_syntax_valid": None}
    try:
        if call.get("type") != "function" or not isinstance(call.get("id"), str) or not call["id"]:
            raise ValueError("Missing function type or tool call ID")
        name = call["function"]["name"]
        schema = next((t["function"]["parameters"] for t in TOOLS if t["function"]["name"] == name), None)
        if schema is None:
            raise ValueError(f"Unknown tool: {name}")
        arguments = json.loads(call["function"]["arguments"])
        validate(arguments, schema)
        result["valid"] = True
        if name == "execute_blender":
            filename = f"generated_{number:02d}.py"
            (store.root / filename).write_text(store.clean(arguments["code"]))
            result["code_file"] = filename
            try:
                ast.parse(arguments["code"])
                result["python_syntax_valid"] = True
            except (SyntaxError, ValueError) as exc:
                result.update(python_syntax_valid=False, python_error=str(exc))
    except (KeyError, TypeError, ValueError, ValidationError) as exc:
        result["error"] = str(exc)
    return result


def run(args):
    output = args.output or ROOT / "runs" / (
        "api_smoke_" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S") + "_" + uuid4().hex[:8])
    config = {k: str(v.resolve()) if isinstance(v, Path) else v for k, v in vars(args).items()}
    config.update(output=str(output.resolve()), max_output_tokens=MAX_OUTPUT_TOKENS,
                  api_timeout=API_TIMEOUT, retries=0, fixture_simulated=True)
    store = Storage(output, args.image, config)
    with Image.open(args.feedback_image) as fixture:
        fixture.convert("RGB").save(store.root / "feedback_fixture.png")
    messages = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": [
        {"type": "text", "text": "API smoke test only: propose one tool call for this reference RGB. "
         "If writing bpy, keep it compact. Generated Python will be saved, never executed."},
        store.image(store.root / "input.png")]}]
    feedback = store.image(store.root / "feedback_fixture.png")
    store.save_system_prompt(messages[0]["content"])
    requests, calls, results = [], [], []
    summary = {"status": "dry_run", "live": args.live, "api_calls": 0,
               "api_calls_definition": "Explicit client attempts; retries disabled, not provider billing count",
               "vision_api_accepted": None, "tool_schema_bundle_accepted": None,
               "native_tool_call_valid": None, "image_feedback_accepted": None,
               "feedback_native_tool_call_valid": None,
               "provider_errors": [], "responses": results, "cost_usd": None,
               "cost_source": "unavailable; no pricing estimate", "python_executed": False,
               "blender_processes": 0, "reconstruction_ready": False,
               "runtime_status": "blocked; this probe does not change runtime readiness"}

    def persist():
        store.write("request_metadata.json", {"model": args.model, "requests": requests,
                    "feedback_transport": "tool text JSON followed by user image_url data URL (LiteLLM adapted)",
                    "feedback_fixture": "feedback_fixture.png", "fixture_simulated": True})
        store.write("tool_calls.json", calls)
        store.write("summary.json", summary)

    for number in (1, 2):
        store.write(f"response_{number:02d}.json", {"status": "not_requested"})
    requests.append({"number": 1, "sent": False, "messages": list(messages), "tools": TOOLS,
                     "tool_choice": "auto", "max_tokens": MAX_OUTPUT_TOKENS})
    persist()
    if not args.live:
        return store.root, store.clean(summary)

    provider = args.model.split("/", 1)[0]
    key_names = {"openai": ("OPENAI_API_KEY",), "anthropic": ("ANTHROPIC_API_KEY",),
                 "gemini": ("GEMINI_API_KEY", "GOOGLE_API_KEY")}.get(provider, ())
    if key_names and not any(os.environ.get(name) for name in key_names):
        summary.update(status="missing_credentials", required_environment=list(key_names))
        persist()
        return store.root, store.clean(summary)

    client = ModelClient(args.model, args.api_base_url)
    for number in range(1, args.max_api_calls + 1):
        if number == 2:
            requests.append({"number": number, "sent": False, "messages": list(messages), "tools": TOOLS,
                             "tool_choice": "auto", "max_tokens": MAX_OUTPUT_TOKENS})
        requests[-1]["sent"] = True
        summary["api_calls"] += 1
        persist()
        started = time.monotonic()
        try:
            reply = client.complete(messages, TOOLS, API_TIMEOUT, max_tokens=MAX_OUTPUT_TOKENS)
        except Exception as exc:
            error = str(exc)
            for url, filename in store.images.items():
                error = error.replace(url, f"[image_file:{filename}]")
            error = store.clean(error)[:2000]
            record = {"number": number, "status": "error", "error_type": type(exc).__name__,
                      "error": error, "latency_seconds": round(time.monotonic() - started, 3),
                      "usage": None, **token_counts(None)}
            results.append(record)
            store.write(f"response_{number:02d}.json", record)
            summary["provider_errors"].append(record)
            summary["status"] = "api_error"
            break
        record = {"number": number, "status": "received", "latency_seconds": round(time.monotonic() - started, 3),
                  "usage": reply.get("usage"), **token_counts(reply.get("usage"))}
        results.append(record)
        store.write(f"response_{number:02d}.json", {**record, "response": reply})
        summary["vision_api_accepted" if number == 1 else "image_feedback_accepted"] = True
        summary["tool_schema_bundle_accepted"] = True
        try:
            choice = reply["choices"][0]
            message = choice["message"]
            record["finish_reason"] = choice.get("finish_reason")
            checked = check_call(message, store, number)
        except (KeyError, IndexError, TypeError) as exc:
            checked = {"valid": False, "error": f"Invalid response structure: {exc}"}
        calls.append({"number": number, **checked})
        summary["native_tool_call_valid" if number == 1 else "feedback_native_tool_call_valid"] = checked["valid"]
        record["python_syntax_valid"] = checked.get("python_syntax_valid")
        if not checked["valid"] or record.get("finish_reason") in ("length", "content_filter"):
            summary["status"] = "protocol_error"
            break
        summary["status"] = "completed" if number == 2 else "first_response_only"
        if number < args.max_api_calls:
            call = checked["call"]
            messages.extend([message, {"role": "tool", "tool_call_id": call["id"],
                "content": json.dumps({"success": False, "executed": False, "simulated": True,
                                       "note": "Tool deliberately not executed. Fixture image follows."})},
                {"role": "user", "content": [{"type": "text", "text": FEEDBACK_NOTE}, feedback]}])
    persist()
    return store.root, store.clean(summary)


def main():
    args = parser().parse_args()
    root, summary = run(args)
    print(json.dumps({"output": str(root), **summary}, indent=2, ensure_ascii=False))
    return 0 if summary["status"] in ("dry_run", "completed", "first_response_only") else 1


if __name__ == "__main__":
    raise SystemExit(main())
